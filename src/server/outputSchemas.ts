/**
 * Declared output shapes for every tool.
 *
 * Without them a caller sees free text and has to infer what a result contains,
 * which is how a footnote gets read as the author's own words or a field gets
 * invented. Declaring the shape makes the distinctions this extension exists to
 * keep straight — matn vs footnote, printed page vs Shamela's automatic count,
 * present on disk vs merely catalogued — part of the contract.
 *
 * Two things govern how these are written.
 *
 * The protocol renders a declared shape with `additionalProperties: false`, so
 * a field a tool RETURNS but does not DECLARE makes the call fail. Declaring a
 * field that never appears costs nothing. The shapes are therefore generated
 * from each tool's own output interface and kept a superset: every field is
 * optional, and the ones carrying meaning we must not blur are typed.
 *
 * `tests/integration/output-schemas.test.ts` calls the tools and checks their
 * responses against these, so a field added later cannot rot the contract
 * silently — it fails in development instead of in someone's session.
 */

